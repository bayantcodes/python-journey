# count() method
# Counts how many times an element occurs in a tuple

numbers = (10, 20, 10, 30, 10, 40)

print(numbers.count(10))


# index() method
# Returns the index of the first occurrence of an element

numbers = (10, 20, 30, 40, 20)

print(numbers.index(20))
